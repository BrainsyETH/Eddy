// Writes src/lib/display/mill-map-data.ts: simplified lines for the six rivers
// the Missouri mills collection reports, drawn by the display's between-mills
// route map. Read-only: it GETs Eddy's public river API (default eddy.guide;
// override with EDDY_BASE_URL) and writes one local file. Re-run only when a
// river's geometry is corrected; the display never fetches geometry itself.
//
//   node scripts/generate-mill-map.mjs

import { writeFile } from 'node:fs/promises';

const base = (process.env.EDDY_BASE_URL || 'https://eddy.guide').replace(/\/$/, '');
const rivers = ['huzzah', 'jacks-fork', 'current', 'eleven-point', 'bryant-creek', 'north-fork-white'];
const TOLERANCE = 0.006; // degrees; about half a kilometre, far below a map pixel.

function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const [ax, ay] = points[0];
  const [bx, by] = points[points.length - 1];
  const dx = bx - ax;
  const dy = by - ay;
  const length = Math.hypot(dx, dy) || 1;
  let worst = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const [px, py] = points[i];
    const distance = Math.abs(dy * px - dx * py + bx * ay - by * ax) / length;
    if (distance > worst) {
      worst = distance;
      index = i;
    }
  }
  if (worst <= tolerance) return [points[0], points[points.length - 1]];
  return [...simplify(points.slice(0, index + 1), tolerance).slice(0, -1), ...simplify(points.slice(index), tolerance)];
}

const lines = {};
for (const slug of rivers) {
  const response = await fetch(`${base}/api/rivers/${slug}`, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`${slug}: HTTP ${response.status}`);
  const coords = (await response.json())?.river?.geometry?.coordinates;
  if (!Array.isArray(coords) || coords.length < 2) throw new Error(`${slug}: no line geometry`);
  lines[slug] = simplify(coords, TOLERANCE).map(([lng, lat]) => [Math.round(lng * 1000) / 1000, Math.round(lat * 1000) / 1000]);
}

const body = Object.entries(lines)
  .map(([slug, points]) => `  '${slug}': ${JSON.stringify(points)},`)
  .join('\n');
await writeFile(
  'src/lib/display/mill-map-data.ts',
  `// Generated by scripts/generate-mill-map.mjs from ${base}/api/rivers/<slug>. Do not edit.\n` +
    `// [lng, lat] pairs, simplified to ${TOLERANCE}° for the between-mills route map.\n` +
    `export const MILL_RIVER_LINES: Record<string, [number, number][]> = {\n${body}\n};\n`
);
console.log(Object.entries(lines).map(([s, p]) => `${s}: ${p.length} points`).join('\n'));
