"""Write the fixture the web app's port of the replay rule is checked against.

Runs the frozen Python replay on a slice of the committed snapshot and saves
its inputs and decisions as JSON. src/lib/arrival-trial/rule.test.ts replays
the same inputs through the TypeScript port and must reproduce every row.

Run: python export_parity_fixture.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

import conditions as c
import lagstudy as ls
import replay as rp

HERE = Path(__file__).parent
TARGET = HERE.parents[2] / "src" / "lib" / "arrival-trial" / "__fixtures__" / "replay-parity.json"
START, END = pd.Timestamp("2026-09-20T00:00:00Z"), pd.Timestamp("2026-11-05T00:00:00Z")


def number(value):
    return None if value is None or not np.isfinite(value) else round(float(value), 6)


def main():
    full = c.load(HERE / "data_conditions" / "development")
    hours = pd.date_range(START, END - ls.HOUR, freq="1h")
    data = {"release": full["release"].reindex(hours), "flows": full["flows"].reindex(hours),
            "stage": full["stage"][(full["stage"].index >= START) & (full["stage"].index < END)],
            "rain": full["rain"]}
    frozen = json.loads((HERE / "results_replay" / "frozen_rule.json").read_text())["frozen"]
    table = rp.replay(data)
    onset = ls.hours(table["onset_time"])
    surge_h, surge_size = c.surge_times(data["stage"], onset)
    issued = table["decision"] == "issued"
    predicted = np.full(len(table), np.nan)
    predicted[issued.to_numpy()] = c.predict(table[issued], frozen["terms"], np.array(frozen["coefficients"]))
    rises = ls.gauge_onsets(data["stage"], "rise", 0.10, 3, 2)
    ms = lambda index: [int(v) for v in (pd.DatetimeIndex(index) - ls.EPOCH) // pd.Timedelta(milliseconds=1)]
    expected = []
    for k, row in table.reset_index(drop=True).iterrows():
        expected.append({
            "hourMs": ms([row["hour"]])[0], "baseline": number(row["baseline"]), "peak": number(row["qpeak"]),
            "priorStep": number(row["pre_step_cfs"]), "stage0": number(row["stage0"]),
            "tributaryRange": number(row["tributary_range_cfs"]), "decision": row["decision"],
            "allReasons": [r for r in row["all_reasons"].split("; ") if r],
            "predictedHours": number(predicted[k]), "withdrawnAfterHours": number(row["withdrawn_after_h"]),
            "gaugeGap": bool(row["gauge_gap"]), "match": row["match"], "delayHours": number(row["delay_h"]),
            "firstRiseAnyHours": number(row["first_rise_any_h"]),
            "steepestRiseHours": number(surge_h[k]), "steepestRiseFtPerHour": number(surge_size[k])})
    stage = data["stage"].dropna()
    fixture = {
        "note": "Generated by scripts/research/bull-shoals-lag-2026-11/export_parity_fixture.py. Do not edit by hand.",
        "model": {"intercept": frozen["coefficients"][0], "lnPeak": frozen["coefficients"][1], "stageFt": frozen["coefficients"][2],
                  "earlyOffsetHours": frozen["range_early_offset_h"], "lateOffsetHours": frozen["range_late_offset_h"]},
        "startHourMs": ms([START])[0],
        "release": [number(v) for v in data["release"].to_numpy(dtype=float)],
        "buffalo": [number(v) for v in data["flows"]["buffalo_cfs"].to_numpy(dtype=float)],
        "crooked": [number(v) for v in data["flows"]["crooked_cfs"].to_numpy(dtype=float)],
        "stage": [[t, float(v)] for t, v in zip(ms(stage.index), stage.to_numpy(dtype=float))],
        "riseMs": ms(rises), "expected": expected}
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(fixture, separators=(",", ":")) + "\n")
    counts = table["decision"].value_counts().to_dict()
    print(TARGET, f"{TARGET.stat().st_size / 1024:.0f} KB", len(expected), "increases", counts,
          table["reason"].value_counts().to_dict(), table["match"].value_counts().to_dict(), "rises", len(rises))


if __name__ == "__main__":
    main()
